export function getSavedPinnedNft(): TelegramNftGift | null {
  try {
    const id = localStorage.getItem("nexus_profile_pinned_nft_id");
    if (id) {
      const found = REAL_TELEGRAM_NFT_GIFTS.find((g) => g.id === id);
      if (found) return found;
    }
  } catch {}
  return REAL_TELEGRAM_NFT_GIFTS[0]; // Default Durov's Cap
}

export function setSavedPinnedNft(id: string | null) {
  if (id) {
    localStorage.setItem("nexus_profile_pinned_nft_id", id);
  } else {
    localStorage.removeItem("nexus_profile_pinned_nft_id");
  }
}
